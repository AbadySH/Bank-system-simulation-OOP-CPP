#!/usr/bin/env python3
"""Rebuild backend/src/SeedData.h from the original project's record files in backend/sample-data/.

Run from the project root:  python3 tools/make_seed_header.py

The sample records are compiled into the program, so the server needs no extra files at run time.
The original login register stored a (weakly encrypted) password on every line; the audit trail in
this edition does not keep passwords, so that column is dropped here.
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "backend", "sample-data")
OUT = os.path.join(ROOT, "backend", "src", "SeedData.h")
SEP = "#//#"


def read_lines(name):
    with open(os.path.join(SRC, name), encoding="utf-8", errors="replace") as f:
        return [line.rstrip("\r\n") for line in f if line.strip()]


def literal(text):
    out = []
    for b in text.encode("utf-8"):
        c = chr(b)
        if c in '\\"':
            out.append("\\" + c)
        elif 32 <= b < 127:
            out.append(c)
        else:
            out.append("\\%03o" % b)       # octal escapes can't swallow the next character
    return '"' + "".join(out) + '"'


login = []
for line in read_lines("LoginRecord.text"):
    f = line.split(SEP)
    if len(f) >= 4:                         # DateTime, UserName, Password, Permissions
        login.append(SEP.join([f[0], f[1], f[3]]))

sets = [
    ("ClientFile", read_lines("ClientFile.txt")),
    ("UsersFile", read_lines("Users.txt")),
    ("CurrenciesFile", read_lines("Currencies.txt")),
    ("LoginRecord", login),
    ("TransferRecord", read_lines("TransferRecord.text")),
]

with open(OUT, "w", encoding="utf-8") as h:
    h.write("// Generated by tools/make_seed_header.py from backend/sample-data/. Do not edit by hand.\n"
            "// PINs and passwords are plain text here and are encrypted when the files are first written.\n"
            "#pragma once\n#include <string>\n#include <vector>\n\nnamespace SeedData\n{\n")
    for name, lines in sets:
        h.write(f"inline const std::vector<std::string> {name} = {{\n")
        for l in lines:
            h.write(f"    {literal(l)},\n")
        h.write("};\n\n")
    h.write("}\n")
print("wrote", OUT, {n: len(l) for n, l in sets})
